@dataclass
class VideoFrame:
    """Represents a single video frame signature"""
    timestamp: int
    confidence: int
    words: List[int]
    frame_signature: List[int]


@dataclass
class VideoSegment:
    """Represents a video segment with bag-of-words features"""
    start_frame: int
    end_frame: int
    start_time: int
    end_time: int
    bag_of_words: List[List[int]]  # 5 bags of 243 bits each


@dataclass
class VideoSignature:
    """Complete MPEG-7 video signature"""
    filename: str
    spatial_region: Tuple[Tuple[int, int], Tuple[int, int]]  # ((x1,y1), (x2,y2))
    time_unit: int
    start_time: int
    end_time: int
    segments: List[VideoSegment]
    frames: List[VideoFrame]
    
    def __post_init__(self):
        """Calculate derived properties for faster comparisons"""
        self.total_frames = len(self.frames)
        self.duration = self.end_time - self.start_time
        self.frame_rate = self.total_frames / (self.duration / self.time_unit) if self.duration > 0 else 0
        
        # Create fingerprint for quick similarity checks
        self._fingerprint = self._calculate_fingerprint()
    
    def _calculate_fingerprint(self) -> str:
        """Calculate a hash fingerprint for quick duplicate detection"""
        # Use representative samples from segments and frames
        fingerprint_data = []
        
        # Sample from segments (use bag-of-words)
        for segment in self.segments[:5]:  # Sample first 5 segments
            for bag in segment.bag_of_words:
                fingerprint_data.extend(bag[:10])  # Sample first 10 words
        
        # Sample from frames
        for frame in self.frames[::max(1, len(self.frames)//10)]:  # Sample every nth frame
            fingerprint_data.extend(frame.words)
            fingerprint_data.extend(frame.frame_signature[:20])  # Sample first 20 bits
        
        return hashlib.md5(str(fingerprint_data).encode()).hexdigest()


class MPEG7SignatureParser:
    """Efficient MPEG-7 signature XML parser with optimizations for large files"""
    
    def __init__(self):
        self.namespace = {"mpeg7": "urn:mpeg:mpeg7:schema:2001"}
    
    def parse_file(self, filepath: str) -> VideoSignature:
        """Parse a single MPEG-7 signature XML file"""
        try:
            # Use iterparse for memory efficiency with large files
            tree = ET.parse(filepath)
            root = tree.getroot()
            
            # Extract video signature region info
            spatial_region = self._extract_spatial_region(root)
            time_info = self._extract_time_info(root)
            
            # Extract segments (coarse signatures)
            segments = self._extract_segments(root)
            
            # Extract individual frames (fine signatures)
            frames = self._extract_frames(root)
            
            return VideoSignature(
                filename=Path(filepath).name,
                spatial_region=spatial_region,
                time_unit=time_info['unit'],
                start_time=time_info['start'],
                end_time=time_info['end'],
                segments=segments,
                frames=frames
            )
            
        except Exception as e:
            raise ValueError(f"Failed to parse {filepath}: {str(e)}")
    
    def _extract_spatial_region(self, root) -> Tuple[Tuple[int, int], Tuple[int, int]]:
        """Extract spatial region coordinates"""
        pixels = root.findall(".//VideoSignatureSpatialRegion/Pixel")
        if len(pixels) >= 2:
            p1 = list(map(int, pixels[0].text.split()))
            p2 = list(map(int, pixels[1].text.split()))
            return ((p1[0], p1[1]), (p2[0], p2[1]))
        return ((0, 0), (0, 0))
    
    def _extract_time_info(self, root) -> Dict[str, int]:
        """Extract temporal information"""
        # Try with and without namespace
        time_unit_elem = root.find(".//MediaTimeUnit") or root.find(".//{urn:mpeg:mpeg7:schema:2001}MediaTimeUnit")
        start_time_elem = root.find(".//StartMediaTimeOfSpatialRegion") or root.find(".//{urn:mpeg:mpeg7:schema:2001}StartMediaTimeOfSpatialRegion")
        end_time_elem = root.find(".//EndMediaTimeOfSpatialRegion") or root.find(".//{urn:mpeg:mpeg7:schema:2001}EndMediaTimeOfSpatialRegion")
        
        time_unit = int(time_unit_elem.text) if time_unit_elem is not None else 1
        start_time = int(start_time_elem.text) if start_time_elem is not None else 0
        end_time = int(end_time_elem.text) if end_time_elem is not None else 0
        
        return {
            'unit': time_unit,
            'start': start_time,
            'end': end_time
        }
    
    def _extract_segments(self, root) -> List[VideoSegment]:
        """Extract video segments with bag-of-words features"""
        segments = []
        
        # Try with and without namespace
        segment_elems = root.findall(".//VSVideoSegment") or root.findall(".//{urn:mpeg:mpeg7:schema:2001}VSVideoSegment")
        
        for segment_elem in segment_elems:
            start_frame_elem = segment_elem.find("StartFrameOfSegment") or segment_elem.find("{urn:mpeg:mpeg7:schema:2001}StartFrameOfSegment")
            end_frame_elem = segment_elem.find("EndFrameOfSegment") or segment_elem.find("{urn:mpeg:mpeg7:schema:2001}EndFrameOfSegment")
            start_time_elem = segment_elem.find(".//StartMediaTimeOfSegment") or segment_elem.find(".//{urn:mpeg:mpeg7:schema:2001}StartMediaTimeOfSegment")
            end_time_elem = segment_elem.find(".//EndMediaTimeOfSegment") or segment_elem.find(".//{urn:mpeg:mpeg7:schema:2001}EndMediaTimeOfSegment")
            
            if start_frame_elem is not None and end_frame_elem is not None and start_time_elem is not None and end_time_elem is not None:
                start_frame = int(start_frame_elem.text)
                end_frame = int(end_frame_elem.text)
                start_time = int(start_time_elem.text)
                end_time = int(end_time_elem.text)
                
                # Extract bag-of-words (5 bags per segment)
                bag_of_words = []
                bag_elems = segment_elem.findall("BagOfWords") or segment_elem.findall("{urn:mpeg:mpeg7:schema:2001}BagOfWords")
                for bag_elem in bag_elems:
                    words = list(map(int, bag_elem.text.split()))
                    bag_of_words.append(words)
                
                segments.append(VideoSegment(
                    start_frame=start_frame,
                    end_frame=end_frame,
                    start_time=start_time,
                    end_time=end_time,
                    bag_of_words=bag_of_words
                ))
        
        return segments
    
    def _extract_frames(self, root) -> List[VideoFrame]:
        """Extract individual frame signatures"""
        frames = []
        
        # Try with and without namespace
        frame_elems = root.findall(".//VideoFrame") or root.findall(".//{urn:mpeg:mpeg7:schema:2001}VideoFrame")
        
        for frame_elem in frame_elems:
            timestamp_elem = frame_elem.find("MediaTimeOfFrame") or frame_elem.find("{urn:mpeg:mpeg7:schema:2001}MediaTimeOfFrame")
            confidence_elem = frame_elem.find("FrameConfidence") or frame_elem.find("{urn:mpeg:mpeg7:schema:2001}FrameConfidence")
            word_elem = frame_elem.find("Word") or frame_elem.find("{urn:mpeg:mpeg7:schema:2001}Word")
            signature_elem = frame_elem.find("FrameSignature") or frame_elem.find("{urn:mpeg:mpeg7:schema:2001}FrameSignature")
            
            if timestamp_elem is not None and confidence_elem is not None and word_elem is not None and signature_elem is not None:
                timestamp = int(timestamp_elem.text)
                confidence = int(confidence_elem.text)
                words = list(map(int, word_elem.text.split()))
                frame_signature = list(map(int, signature_elem.text.split()))
                
                frames.append(VideoFrame(
                    timestamp=timestamp,
                    confidence=confidence,
                    words=words,
                    frame_signature=frame_signature
                ))
        
        return frames


class SignatureComparator:
    """High-performance signature comparison engine"""
    
    def __init__(self, word_threshold: int = 9000, composition_threshold: int = 60000):
        self.word_threshold = word_threshold
        self.composition_threshold = composition_threshold
    
    def compare_signatures(self, sig1: VideoSignature, sig2: VideoSignature) -> Dict:
        """Compare two video signatures and return similarity metrics"""
        start_time = time.time()
        
        # Quick fingerprint check for exact duplicates
        if sig1._fingerprint == sig2._fingerprint:
            return {
                'similarity_score': 1.0,
                'segment_similarity': 1.0,
                'frame_similarity': 1.0,
                'temporal_similarity': 1.0,
                'is_duplicate': True,
                'is_similar': True,
                'comparison_time': time.time() - start_time,
                'method': 'fingerprint_match'
            }
        
        # Segment-level comparison (coarse signatures)
        segment_similarity = self._compare_segments(sig1.segments, sig2.segments)
        
        # Frame-level comparison (fine signatures) - sample for performance
        frame_similarity = self._compare_frames_sampled(sig1.frames, sig2.frames)
        
        # Temporal alignment analysis
        temporal_similarity = self._compare_temporal_alignment(sig1, sig2)
        
        # Combined similarity score
        combined_score = (
            segment_similarity * 0.4 +
            frame_similarity * 0.4 +
            temporal_similarity * 0.2
        )
        
        return {
            'similarity_score': combined_score,
            'segment_similarity': segment_similarity,
            'frame_similarity': frame_similarity,
            'temporal_similarity': temporal_similarity,
            'is_duplicate': combined_score > 0.95,
            'is_similar': combined_score > 0.8,
            'comparison_time': time.time() - start_time,
            'method': 'multi_level_analysis'
        }
    
    def _compare_segments(self, segments1: List[VideoSegment], segments2: List[VideoSegment]) -> float:
        """Compare video segments using bag-of-words features"""
        if not segments1 or not segments2:
            return 0.0
        
        # Sample segments for performance (use every nth segment)
        sample_rate = max(1, max(len(segments1), len(segments2)) // 10)
        sampled_seg1 = segments1[::sample_rate]
        sampled_seg2 = segments2[::sample_rate]
        
        similarities = []
        
        for seg1 in sampled_seg1:
            best_similarity = 0.0
            for seg2 in sampled_seg2:
                sim = self._segment_similarity(seg1, seg2)
                best_similarity = max(best_similarity, sim)
            similarities.append(best_similarity)
        
        return np.mean(similarities) if similarities else 0.0
    
    def _segment_similarity(self, seg1: VideoSegment, seg2: VideoSegment) -> float:
        """Calculate similarity between two segments"""
        if len(seg1.bag_of_words) != len(seg2.bag_of_words):
            return 0.0
        
        bag_similarities = []
        
        for bag1, bag2 in zip(seg1.bag_of_words, seg2.bag_of_words):
            if len(bag1) == len(bag2):
                # Use Hamming distance for binary features
                hamming_dist = sum(abs(a - b) for a, b in zip(bag1, bag2))
                similarity = 1.0 - (hamming_dist / len(bag1))
                bag_similarities.append(similarity)
        
        return np.mean(bag_similarities) if bag_similarities else 0.0
    
    def _compare_frames_sampled(self, frames1: List[VideoFrame], frames2: List[VideoFrame]) -> float:
        """Compare frames using sampling for performance"""
        if not frames1 or not frames2:
            return 0.0
        
        # Sample frames (use every nth frame)
        sample_rate = max(1, max(len(frames1), len(frames2)) // 20)
        sampled_frames1 = frames1[::sample_rate]
        sampled_frames2 = frames2[::sample_rate]
        
        similarities = []
        
        for frame1 in sampled_frames1:
            best_similarity = 0.0
            for frame2 in sampled_frames2:
                sim = self._frame_similarity(frame1, frame2)
                best_similarity = max(best_similarity, sim)
            similarities.append(best_similarity)
        
        return np.mean(similarities) if similarities else 0.0
    
    def _frame_similarity(self, frame1: VideoFrame, frame2: VideoFrame) -> float:
        """Calculate similarity between two frames"""
        # Compare word features
        word_similarity = 1.0 - (sum(abs(a - b) for a, b in zip(frame1.words, frame2.words)) / len(frame1.words))
        
        # Compare frame signatures (sample for performance)
        sig_sample_size = min(50, len(frame1.frame_signature), len(frame2.frame_signature))
        sig1_sample = frame1.frame_signature[:sig_sample_size]
        sig2_sample = frame2.frame_signature[:sig_sample_size]
        
        signature_similarity = 1.0 - (sum(abs(a - b) for a, b in zip(sig1_sample, sig2_sample)) / sig_sample_size)
        
        return (word_similarity + signature_similarity) / 2
    
    def _compare_temporal_alignment(self, sig1: VideoSignature, sig2: VideoSignature) -> float:
        """Compare temporal characteristics"""
        # Compare duration
        duration_ratio = min(sig1.duration, sig2.duration) / max(sig1.duration, sig2.duration) if max(sig1.duration, sig2.duration) > 0 else 0
        
        # Compare frame rates
        frame_rate_ratio = min(sig1.frame_rate, sig2.frame_rate) / max(sig1.frame_rate, sig2.frame_rate) if max(sig1.frame_rate, sig2.frame_rate) > 0 else 0
        
        # Compare total frames
        frame_count_ratio = min(sig1.total_frames, sig2.total_frames) / max(sig1.total_frames, sig2.total_frames) if max(sig1.total_frames, sig2.total_frames) > 0 else 0
        
        return (duration_ratio + frame_rate_ratio + frame_count_ratio) / 3


class BatchProcessor:
    """Efficient batch processing for large datasets"""
    
    def __init__(self, max_workers: int = None):
        self.parser = MPEG7SignatureParser()
        self.comparator = SignatureComparator()
        self.max_workers = max_workers or 4
    
    def process_directory(self, directory: str, output_file: str = None) -> Dict:
        """Process all XML files in a directory and generate comparison matrix"""
        xml_files = list(Path(directory).glob("*.xml"))
        
        print(f"Found {len(xml_files)} XML files to process...")
        
        # Parse all files
        signatures = {}
        with ProcessPoolExecutor(max_workers=self.max_workers) as executor:
            future_to_file = {executor.submit(self.parser.parse_file, str(f)): f for f in xml_files}
            
            for future in as_completed(future_to_file):
                file_path = future_to_file[future]
                try:
                    signature = future.result()
                    signatures[signature.filename] = signature
                    print(f"Parsed: {signature.filename}")
                except Exception as e:
                    print(f"Error parsing {file_path}: {e}")
        
        # Generate comparison matrix
        print("Generating comparison matrix...")
        comparison_matrix = self._generate_comparison_matrix(signatures)
        
        if output_file:
            self._save_results(comparison_matrix, output_file)
        
        return comparison_matrix
    
    def _generate_comparison_matrix(self, signatures: Dict[str, VideoSignature]) -> Dict:
        """Generate a comparison matrix for all signatures"""
        files = list(signatures.keys())
        results = {
            'files': files,
            'comparisons': {},
            'duplicates': [],
            'similar_pairs': [],
            'statistics': {}
        }
        
        total_comparisons = len(files) * (len(files) - 1) // 2
        comparison_count = 0
        
        for i, file1 in enumerate(files):
            for j, file2 in enumerate(files[i+1:], i+1):
                comparison_result = self.comparator.compare_signatures(
                    signatures[file1], 
                    signatures[file2]
                )
                
                results['comparisons'][f"{file1} vs {file2}"] = comparison_result
                
                if comparison_result['is_duplicate']:
                    results['duplicates'].append((file1, file2, comparison_result['similarity_score']))
                elif comparison_result['is_similar']:
                    results['similar_pairs'].append((file1, file2, comparison_result['similarity_score']))
                
                comparison_count += 1
                if comparison_count % 100 == 0:
                    print(f"Progress: {comparison_count}/{total_comparisons} comparisons completed")
        
        # Calculate statistics
        similarities = [comp['similarity_score'] for comp in results['comparisons'].values()]
        results['statistics'] = {
            'total_files': len(files),
            'total_comparisons': total_comparisons,
            'duplicates_found': len(results['duplicates']),
            'similar_pairs_found': len(results['similar_pairs']),
            'average_similarity': np.mean(similarities),
            'median_similarity': np.median(similarities),
            'max_similarity': max(similarities),
            'min_similarity': min(similarities)
        }
        
        return results
    
    def _save_results(self, results: Dict, output_file: str):
        """Save results to JSON file"""
        with open(output_file, 'w') as f:
            json.dump(results, f, indent=2, default=str)
        print(f"Results saved to: {output_file}")


def main():
    parser = argparse.ArgumentParser(description="MPEG-7 Video Signature Analysis Tool")
    parser.add_argument("input", help="Input XML file or directory")
    parser.add_argument("-o", "--output", help="Output JSON file for results")
    parser.add_argument("-c", "--compare", help="Compare with another XML file")
    parser.add_argument("--batch", action="store_true", help="Process directory in batch mode")
    parser.add_argument("--workers", type=int, default=4, help="Number of worker processes")
    
    args = parser.parse_args()
    
    if args.batch:
        processor = BatchProcessor(max_workers=args.workers)
        results = processor.process_directory(args.input, args.output)
        
        print("\n=== ANALYSIS RESULTS ===")
        stats = results['statistics']
        print(f"Total files processed: {stats['total_files']}")
        print(f"Duplicates found: {stats['duplicates_found']}")
        print(f"Similar pairs found: {stats['similar_pairs_found']}")
        print(f"Average similarity: {stats['average_similarity']:.3f}")
        
    else:
        # Single file or comparison mode
        mpeg7_parser = MPEG7SignatureParser()
        comparator = SignatureComparator()
        
        sig1 = mpeg7_parser.parse_file(args.input)
        print(f"Parsed signature: {sig1.filename}")
        print(f"Duration: {sig1.duration}, Frames: {sig1.total_frames}, Segments: {len(sig1.segments)}")
        
        if args.compare:
            sig2 = mpeg7_parser.parse_file(args.compare)
            result = comparator.compare_signatures(sig1, sig2)
            
            print(f"\n=== COMPARISON RESULTS ===")
            print(f"Overall similarity: {result['similarity_score']:.3f}")
            print(f"Segment similarity: {result['segment_similarity']:.3f}")
            print(f"Frame similarity: {result['frame_similarity']:.3f}")
            print(f"Temporal similarity: {result['temporal_similarity']:.3f}")
            print(f"Is duplicate: {result['is_duplicate']}")
            print(f"Is similar: {result['is_similar']}")
            print(f"Comparison time: {result['comparison_time']:.3f}s")


if __name__ == "__main__":
    main()